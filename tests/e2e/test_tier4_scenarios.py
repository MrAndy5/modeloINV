# Scenario 3: Broker-Agnostic Switching (Paper to Live via Config Only)
# =====================================================================

class TestScenario3BrokerAgnosticSwitching:
    """Acceptance Criteria:
    - Broker abstraction layer has documented BaseBroker interface.
    - Working implementation (SimulatedPaperBroker, AlpacaPaperBroker).
    - Switching from paper to live requires only configuration change, ZERO code change.
    - Strict €100 virtual partition maintained.
    """

    def test_zero_code_broker_switching(self, monkeypatch):
        # Factory method switching broker based strictly on environment config
        def get_configured_broker(eur_usd_rate: float = 1.08):
            mode = os.getenv("MODELOINV_EXECUTION_MODE", "paper")
            initial_cap = float(os.getenv("MODELOINV_STARTING_CAPITAL", "100.0"))
            
            if mode == "paper":
                broker = OfflineSimulatedBroker(initial_capital_eur=initial_cap, eur_usd_rate=eur_usd_rate)
                broker.is_live = False
                return broker
            elif mode == "live":
                # Alpaca sandbox partition broker
                broker = OfflineSimulatedBroker(initial_capital_eur=initial_cap, eur_usd_rate=eur_usd_rate)
                broker.is_live = True
                return broker
            else:
                raise ValueError(f"Unknown mode: {mode}")

        # 1. Execute in Paper Mode
        monkeypatch.setenv("MODELOINV_EXECUTION_MODE", "paper")
        broker_paper = get_configured_broker()
        assert broker_paper.is_live is False
        acc_paper = broker_paper.get_account()
        assert acc_paper.is_live is False
        assert acc_paper.initial_capital_eur == 100.0

        order_paper = OrderRequest(symbol="SPY", side=OrderSide.BUY, order_type=OrderType.MARKET, notional=20.0)
        res_paper = broker_paper.submit_order(order_paper, current_market_price=450.0)
        assert res_paper.status == OrderStatus.FILLED

        # 2. Switch strictly via configuration to Live Mode
        monkeypatch.setenv("MODELOINV_EXECUTION_MODE", "live")
        broker_live = get_configured_broker()
        assert broker_live.is_live is True
        acc_live = broker_live.get_account()
        assert acc_live.is_live is True
        assert acc_live.initial_capital_eur == 100.0  # €100 virtual partition

        # Same identical order logic runs with ZERO code modification
        order_live = OrderRequest(symbol="SPY", side=OrderSide.BUY, order_type=OrderType.MARKET, notional=20.0)
        res_live = broker_live.submit_order(order_live, current_market_price=450.0)
        assert res_live.status == OrderStatus.FILLED
        assert res_live.filled_quantity == res_paper.filled_quantity


